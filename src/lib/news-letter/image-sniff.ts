/**
 * The real type of an uploaded image, read from its first bytes — the file name and the browser's Content-Type are
 * never trusted. Only raster formats a browser shows without running anything: PNG, JPEG, WebP, GIF. SVG is refused on
 * purpose (it can carry script).
 */
export type NewsLetterImageMime = 'image/png' | 'image/jpeg' | 'image/webp' | 'image/gif';

export function sniffImageMime(bytes: Uint8Array): NewsLetterImageMime | null {
  if (bytes.length < 12) return null;
  if (bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4e && bytes[3] === 0x47 && bytes[4] === 0x0d && bytes[5] === 0x0a && bytes[6] === 0x1a && bytes[7] === 0x0a) return 'image/png';
  if (bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) return 'image/jpeg';
  if (bytes[0] === 0x52 && bytes[1] === 0x49 && bytes[2] === 0x46 && bytes[3] === 0x46 && bytes[8] === 0x57 && bytes[9] === 0x45 && bytes[10] === 0x42 && bytes[11] === 0x50) return 'image/webp';
  if (bytes[0] === 0x47 && bytes[1] === 0x49 && bytes[2] === 0x46 && bytes[3] === 0x38 && (bytes[4] === 0x37 || bytes[4] === 0x39) && bytes[5] === 0x61) return 'image/gif';
  return null;
}
